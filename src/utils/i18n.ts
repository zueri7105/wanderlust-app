export function getTranslation(key: string, lang?: string): string {
  const currentLang = (lang || localStorage.getItem('wanderlust_app_lang') || 'en') as AppLanguage;
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  const viewDict = VIEW_STRINGS[currentLang] || VIEW_STRINGS.en;
  return dict[key] || viewDict[key] || VIEW_STRINGS.en[key] || TRANSLATIONS.en[key] || key;
}

export function playAudioAlert() {
  try {
    const AudioCtx = window.AudioContext || (window as any).webkitAudioContext;
    if (!AudioCtx) return;
    const ctx = new AudioCtx();
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = 'sine';
    // Pleasant dual chime
    osc.frequency.setValueAtTime(587.33, ctx.currentTime); // D5
    osc.frequency.setValueAtTime(880, ctx.currentTime + 0.12); // A5

    gain.gain.setValueAtTime(0.15, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.4);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start();
    osc.stop(ctx.currentTime + 0.45);
  } catch (e) {
    console.warn('Web Audio playback error:', e);
  }
}
